#!/usr/bin/env python3
"""Generate carterkit/typed.py: one explicitly typed method per control kind.

Reads the bundled ControlDocs (via the catalog) so editors (Pylance/pyright)
autocomplete and type-check every field of `ui.gauge(...)` / `build.gauge(...)`.
Runtime behaviour is unchanged: the methods only forward to the existing
`_make` / `controls.control` machinery.

    python3 scripts/gen-typed-controls.py           # rewrite carterkit/typed.py
    python3 scripts/gen-typed-controls.py --check   # exit 1 if typed.py is stale
"""
from __future__ import annotations

import keyword
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "carterkit" / "typed.py"

# Keyword-only params `Layout._make` handles itself; a doc field with one of these
# names is covered by the common param instead of getting a second one.
SCOPE_COMMON = [
    ("id", "str | None", "None"),
    ("position", "Sequence[int] | None", "None"),
    ("span", "Sequence[int] | None", "None"),
    ("listen", "str | Sequence[str] | None", "None"),
    ("when", "Any", "None"),
    ("event", "str", '"broadcast"'),
    ("send", "str | None", "None"),
    ("request", "bool", "False"),
    ("payload", "Any", "None"),
    ("sensor", "str | Sequence[str] | None", "None"),
    ("sync", "Sequence[dict[str, Any]] | None", "None"),
    ("action", "Any", "None"),
    ("visible", "Any", "None"),
    ("enabled", "Any", "None"),
    ("pulse", "Any", "None"),
    ("fallback", "Any", "None"),
]
BUILD_COMMON = [
    ("id", "str", None),          # required
    ("position", "Sequence[int] | None", "None"),
    ("span", "Sequence[int] | None", "None"),
]

SCALAR = {
    "number": "_Num", "bool": "_Bool", "string": "_Str", "color": "_Str",
    "array": "_Arr", "string[]": "_StrList", "object": "_Obj", "object[]": "_ObjList",
}

HEADER = '''"""GENERATED by scripts/gen-typed-controls.py from the bundled ControlDocs — do not edit.

Explicitly typed control factories so editors autocomplete and type-check every
field. `ScopeControls` is mixed into Layout / tab / group / Fragment scopes
(returns a `Control` handle); `BuildControls` backs `carterkit.build` (returns
the control dict). Nested object / array fields are typed `dict[str, Any]` /
`list[Any]` because the docs carry no sub-schema; unknown props still pass
through `**props` (forward-compatible, as at runtime).
"""
from __future__ import annotations

from collections.abc import Sequence
from typing import TYPE_CHECKING, Any, Literal

if TYPE_CHECKING:
    from .layout import Control

_Num = float
_Bool = bool
_Str = str
_Arr = list[Any]
_StrList = list[str]
_Obj = dict[str, Any]
_ObjList = list[dict[str, Any]]
'''


def snake(t: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "_", t).lower()


def pytype(f: dict) -> str:
    if f.get("type") == "enum" and f.get("values"):
        return "Literal[" + ", ".join(repr(v) for v in f["values"]) + "]"
    return SCALAR.get(f.get("type", "string"), "Any")


def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"""', '\\"\\"\\"').strip()


def fields_of(spec: dict, reserved: set[str]) -> list[dict]:
    seen, out = set(), []
    for f in spec.get("fields", []):
        n = f.get("name", "")
        if (not n.isidentifier() or keyword.iskeyword(n) or n in reserved
                or n in seen or n.startswith("_")):
            continue
        seen.add(n)
        out.append(f)
    return out


def method(ctype: str, spec: dict, common, ret: str, call: str) -> str:
    reserved = {c[0] for c in common} | {"props", "self"}
    fs = fields_of(spec, reserved)
    params = []
    for n, t, d in common:
        params.append(f"{n}: {t}" if d is None else f"{n}: {t} = {d}")
    # Layout scopes accept the id positionally (`ui.button("b", ...)`), as before.
    lead = "self, " if common[0][2] is None else "self, " + params.pop(0) + ", *,"
    if common[0][2] is None:
        lead = "self, *,"
    for f in fs:
        params.append(f"{f['name']}: {pytype(f)} | None = None")
    params.append("**props: Any")
    sig = ",\n        ".join(params)
    head = spec.get("friendlyName") or spec.get("label") or ctype
    one = spec.get("oneLiner") or ""
    doc = [f"{head}" + (f": {one}" if one else ""), f"(catalog type `{ctype}`)"]
    if fs:
        doc.append("")
        doc.append("Fields:")
        for f in fs:
            d = (f.get("description") or f.get("title") or "").strip()
            doc.append(f"    {f['name']}: {d}" if d else f"    {f['name']}")
    doc_s = "\n".join(("        " + ln).rstrip() for ln in esc("\n".join(doc)).split("\n")).lstrip()
    names = [c[0] for c in common] + [f["name"] for f in fs]
    kw = ", ".join(f"{n}={n}" for n in names)
    return (f"    def {snake(ctype)}(\n        {lead}\n        {sig},\n    ) -> {ret}:\n"
            f'        """{doc_s}\n        """\n'
            f'        return {call}("{ctype}", dict({kw}), props)\n')


def generate() -> str:
    sys.path.insert(0, str(ROOT))
    import carterkit  # noqa: F401  (populates sys.modules)
    cat = sys.modules["carterkit.controls"]._catalog()
    parts = [HEADER, "\nclass ScopeControls:\n"
             '    """Typed control methods for a placeable scope; subclasses supply `_ctl`."""\n\n'
             '    def _ctl(self, ctype: str, kw: dict[str, Any], props: dict[str, Any]) -> "Control":\n'
             "        raise NotImplementedError\n"]
    for t in sorted(cat):
        parts.append("\n" + method(t, cat[t], SCOPE_COMMON, '"Control"', "self._ctl"))
    parts.append("\n\nclass BuildControls:\n"
                 '    """Typed control builders returning the validated control dict."""\n\n'
                 "    def _ctl(self, ctype: str, kw: dict[str, Any], props: dict[str, Any]) -> dict[str, Any]:\n"
                 "        raise NotImplementedError\n")
    for t in sorted(cat):
        parts.append("\n" + method(t, cat[t], BUILD_COMMON, "dict[str, Any]", "self._ctl"))
    return "".join(parts)


def main() -> int:
    text = generate()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print("carterkit/typed.py is stale: run python3 scripts/gen-typed-controls.py",
                  file=sys.stderr)
            return 1
        print("typed.py is fresh")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
